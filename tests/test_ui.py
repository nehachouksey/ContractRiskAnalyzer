import tempfile, unittest
from pathlib import Path
from streamlit.testing.v1 import AppTest
from src import core as c
class UITests(unittest.TestCase):
 def setUp(self):
  self.temp=tempfile.TemporaryDirectory(); self.old=c.STORE; c.STORE=Path(self.temp.name)
 def tearDown(self): c.STORE=self.old; self.temp.cleanup()
 def test_intake_and_missing_credentials(self):
  app=AppTest.from_file('app.py', default_timeout=60).run()
  self.assertFalse(app.exception)
  app.text_input[0].set_value('UI tester'); app.text_input[1].set_value('test-only-password-123')
  app.button[0].click().run()
  app.run()
  self.assertFalse(app.exception)
  self.assertEqual(len([b for b in app.button if b.key!='sign_out']),15)
  next(b for b in app.button if b.key not in ['sign_out',None]).click().run()
  self.assertFalse(app.exception)
  self.assertIn('Incoming',str(app).title())
  app.checkbox[0].check()
  next(b for b in app.button if b.label=='Analyse contract').click().run()
  self.assertFalse(app.exception)
  self.assertTrue(any('Analysis failed' in e.value for e in app.error))
  self.assertEqual(c.history('UI tester')[0]['status'],'analysis_failed')
 def test_assessment_journey_test_fixture_only(self):
  from unittest.mock import patch
  c.setup('tester','test-only-password-123')
  incoming=c.documents('tester','incoming')[0]; historical=c.documents('tester','signed_contracts')[0]
  fixture={'comparisons':[{'historical_id':historical['id'],'outcome':'Insufficient evidence','title':'Automated test fixture only','explanation':'Test of review controls; not a real analysis.','scope':'Scope requires clarification.','dates':'Dates require confirmation.','clarification':'Request supporting evidence.','evidence':[{'source_id':incoming['id'],'version':incoming['version'],'line':1,'clause':'Original source','quote':incoming['text'][:60]}]}], 'coverage':[{'source_id':d['id'],'status':'incomplete','reason':'Test fixture'} for d in c.documents('tester','signed_contracts')], 'duration':0,'model':'test-only'}
  app=AppTest.from_file('app.py',default_timeout=60).run()
  app.text_input[0].set_value('tester'); app.text_input[1].set_value('test-only-password-123'); app.button[0].click().run()
  app.run()
  next(b for b in app.button if b.key not in ['sign_out',None]).click().run(); app.checkbox[0].check()
  with patch.object(c,'analyze',return_value=fixture): next(b for b in app.button if b.label=='Analyse contract').click().run()
  self.assertFalse(app.exception)
  self.assertTrue(any('document checks are unfinished' in x.value for x in app.warning))
  rationale=next(t for t in app.text_area if t.label=='Assessment rationale')
  rationale.set_value('Test rationale retained across evidence changes').run()
  app.toggle[0].set_value(True).run()
  self.assertFalse(app.exception)
  self.assertEqual(next(t for t in app.text_area if t.label=='Assessment rationale').value,'Test rationale retained across evidence changes')
  next(b for b in app.button if b.label in ['Save & next','Save assessment & continue to decision']).click().run()
  self.assertFalse(app.exception)
  self.assertEqual(len(c.history('tester')[0]['assessments']),1)
  next(x for x in app.radio if x.label=='Your decision').set_value('Need more information').run()
  next(x for x in app.text_area if x.label=='Why is this your decision?').set_value('Request the missing supporting documents').run()
  next(x for x in app.checkbox if x.label.startswith('I have reviewed the evidence')).check().run()
  next(b for b in app.button if b.key=='save_review_decision').click().run()
  self.assertNotIn('completion',c.history('tester')[0])
  self.assertEqual(c.history('tester')[0]['decisions'][-1]['workflow_status'],'follow_up')
  next(r for r in app.radio if r.label=='Workspace navigation').set_value('Review history').run()
  self.assertFalse(app.exception)
  next(r for r in app.radio if r.label=='Workspace navigation').set_value('Review workspace').run()
  next(b for b in app.button if b.label=='2. Review findings').click().run()
  self.assertEqual(next(t for t in app.text_area if t.label=='Assessment rationale').value,'Test rationale retained across evidence changes')
 def test_complete_review_controls(self):
  c.setup('tester','test-only-password-123')
  incoming=c.documents('tester','incoming')[0]; historical=c.documents('tester','signed_contracts')[0]
  run={'id':'ui-completion','reviewer':'tester','created':c.now(),'incoming_id':incoming['id'],'name':incoming['name'],'version':incoming['version'],'context':{'entity':'Unknown','scope':'Synthetic UI test scope','review_date':'2026-09-28'},'snapshot':c.snapshot('tester'),'duration':0,'coverage':[{'source_id':historical['id'],'status':'assessed','reason':'Test fixture'}],'comparisons':[{'historical_id':historical['id'],'outcome':'No conflict identified in this comparison','title':'Isolated UI fixture','explanation':'Test controls only','scope':'Test scope','dates':'Test dates','clarification':'None','evidence':[]}],'assessments':[{'comparison':0,'action':'Confirm finding','rationale':'Test rationale','reviewer':'tester','time':c.now()}],'decisions':[]}
  import copy
  run['comparisons'].append(copy.deepcopy(run['comparisons'][0]))
  run['comparisons'][1]['title']='Second isolated fixture'
  run['assessments'].append({**run['assessments'][0],'comparison':1})
  app=AppTest.from_file('app.py',default_timeout=60)
  app.session_state['user']='tester'; app.session_state['active']=incoming['id']; app.session_state['run']=run; app.session_state['page']='Review workspace'; app.session_state['step_'+incoming['id']]=3; app.run()
  self.assertFalse(app.exception)
  next(b for b in app.button if b.label=='2. Review findings').click().run()
  self.assertTrue(any(x.value=='Finding 1 of 2' for x in app.subheader))
  next(b for b in app.button if b.label=='Next finding').click().run()
  self.assertTrue(any(x.value=='Finding 2 of 2' for x in app.subheader))
  self.assertNotIn('Accept supported risk',app.selectbox[0].options)
  next(b for b in app.button if b.label=='Previous finding').click().run()
  next(b for b in app.button if b.label in ['Save & next','Save assessment & continue to decision']).click().run()
  self.assertTrue(any(x.value=='Finding 2 of 2' for x in app.subheader))
  app.run()
  next(b for b in app.button if b.label in ['Save & next','Save assessment & continue to decision']).click().run()
  app.run()
  self.assertFalse(app.exception)
  self.assertFalse(app.error)
  self.assertFalse(any(b.label=='Complete review' for b in app.button))
  next(x for x in app.radio if x.label=='Your decision').set_value('Proceed for signing approval').run()
  next(b for b in app.button if b.key=='save_review_decision').click().run()
  self.assertTrue(any('rationale' in e.value for e in app.error))
  next(x for x in app.text_area if x.label=='Why is this your decision?').set_value('All fixture evidence inspected; refer to signatory').run()
  next(x for x in app.checkbox if x.label.startswith('I have reviewed the evidence')).check().run()
  next(b for b in app.button if b.key=='save_review_decision').click().run()
  self.assertFalse(app.exception)
  self.assertIn('completion',c.history('tester')[0])
  app.run()
  self.assertFalse(any(b.key=='save_review_decision' for b in app.button))
  next(b for b in app.button if b.label=='2. Review findings').click().run()
  self.assertTrue(next(b for b in app.button if b.label in ['Save & next','Save assessment & continue to decision']).disabled)
  next(b for b in app.button if b.label=='Sign out').click().run()
  self.assertNotIn('user',app.session_state)
  self.assertNotIn('run',app.session_state)
  app=AppTest.from_file('app.py',default_timeout=60).run()
  self.assertFalse(app.exception)
  self.assertFalse(any(b.label=='Sign out' for b in app.button))
  self.assertTrue(any(t.label=='Password' for t in app.text_input))
  self.assertNotIn('user',app.session_state)
  self.assertNotIn('run',app.session_state)
  self.assertIn('completion',c.history('tester')[0])
if __name__=='__main__': unittest.main()
